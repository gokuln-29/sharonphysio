import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const output = ts.transpileModule(readFileSync('src/lib/appointment.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { clinicToday, normalizePhone, validateAppointment, appointmentMessage } = await import(`data:text/javascript;base64,${Buffer.from(output).toString('base64')}`);
const base = { name: 'Test visitor', phone: '+91 98765 43210', treatment: '', preferredDate: '', preferredSlot: '', message: '' };
assert.equal(clinicToday(new Date('2026-11-18T20:00:00Z')), '2026-11-19');
assert.equal(normalizePhone(base.phone), '9876543210');
assert.deepEqual(validateAppointment(base, '2026-11-18'), {});
assert.ok(validateAppointment({ ...base, name: ' ' }, '2026-11-18').name);
assert.ok(validateAppointment({ ...base, phone: '1234567890' }, '2026-11-18').phone);
assert.ok(validateAppointment({ ...base, preferredDate: '2026-11-17' }, '2026-11-18').preferredDate);
assert.ok(validateAppointment({ ...base, preferredDate: '2026-11-22' }, '2026-11-18').preferredDate);
assert.ok(validateAppointment({ ...base, preferredDate: '2027-02-30' }, '2026-11-18').preferredDate);
assert.deepEqual(validateAppointment({ ...base, preferredDate: '2026-11-21' }, '2026-11-18'), {});
assert.match(appointmentMessage({ ...base, treatment: 'stroke' }), /Stroke Rehabilitation/);
assert.match(appointmentMessage(base), /Please confirm availability/);
assert.doesNotMatch(appointmentMessage({ ...base, treatment: '<unknown>' }), /unknown/);
console.log('12 appointment checks passed: phone formatting, required fields, India dates, Sunday closure and message content.');
